#!/usr/bin/env python3
"""Emit tcq3_constants.h from the llama.cpp TurboQuant fork.

The codebooks and sign tables are fitted values. Transcribing them by hand
risks a silent quality regression, so read them out of the fork instead.
"""

import os
import pathlib
import re

# Override with TURBOQUANT_FORK when the fork lives somewhere else.
FORK = pathlib.Path(
    os.environ.get("TURBOQUANT_FORK", "~/code/llama-turboquant/llama-cpp-turboquant")
).expanduser()
SRC = FORK / "ggml" / "src" / "ggml-cuda" / "turbo-quant-cuda.cuh"
DST = pathlib.Path(__file__).with_name("tcq3_constants.h")

TABLES = {
    "kTcq3CodebookK": ("d_turbo3_tcq_codebook", 512),
    "kTcq3CodebookV": ("d_turbo3_tcq_codebook_v", 512),
    "kWhtSigns1": ("d_turbo_wht_signs1", 128),
    "kWhtSigns2": ("d_turbo_wht_signs2", 128),
}


def grab(text, name, count):
    match = re.search(re.escape(name) + r"\[" + str(count) + r"\]\s*=\s*\{(.*?)\};", text, re.S)
    if not match:
        raise SystemExit(f"{name} not found in {SRC}")
    values = re.findall(r"-?\d+\.?\d*(?:[eE][-+]?\d+)?f", match.group(1))
    if len(values) != count:
        raise SystemExit(f"{name}: found {len(values)} values, expected {count}")
    return [v.rstrip("f") for v in values]


def main():
    text = SRC.read_text()
    out = [
        "// Generated by extract-constants.py from the llama.cpp TurboQuant fork.",
        "// Do not edit. Re-run the script if the fork's tables change.",
        "#pragma once",
        "",
    ]
    for emitted, (symbol, count) in TABLES.items():
        values = grab(text, symbol, count)
        out.append(f"static const float {emitted}[{count}] = {{")
        for i in range(0, count, 8):
            out.append("    " + " ".join(f"{v}f," for v in values[i : i + 8]))
        out.append("};")
        out.append("")
    out += [
        "// Alpha factors.",
        "//",
        "// The fork compiles an encode-time V alpha of 1.04, but overrides it to 1.0 at",
        "// startup unless TURBO_TCQ_ENCODE_ALPHA is set, and applies 1.02 at decode time",
        "// instead. The startup log line reads \"TCQ: encode V alpha=1.0",
        "// (context-adaptive decode-time alpha active)\". The deployed configuration is",
        "// therefore encode 1.0 for both K and V, decode 1.0 for K and 1.02 for V, and",
        "// that is what the measured perplexity of 5.8327 used.",
        "static const float kTcq3NormAlphaK = 1.0f;",
        "static const float kTcq3NormAlphaV = 1.0f;",
        "static const float kTcq3DecodeAlphaK = 1.0f;",
        "static const float kTcq3DecodeAlphaV = 1.02f;",
        "",
    ]
    DST.write_text("\n".join(out))
    print(f"wrote {DST}")


if __name__ == "__main__":
    main()
